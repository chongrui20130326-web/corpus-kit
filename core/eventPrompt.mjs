import { COMMON } from './prompts.mjs';

/** 类型归一：一次看完所有事件，统一标准，避免分批判断飘移。 */
export function pEventTypes({ events }) {
  return `【任务】给下面每一条关键事件指定唯一一个类型。所有事件的判断标准必须一致。

类型定义（只能选一个）：
- 关系转变：人物之间的关系性质变了，例如陌生变亲密、亲属变情人、上下级变情人。
- 权力转变：主导方或自愿程度变了，例如自愿变强迫、被动变主动、平等变支配。
- 心理突破：内心防线或自我认知变了，例如羞耻变接受、抗拒变渴望、清醒变失控。
- 身体越界：第一次发生某种身体行为，或越过了原本不接受的身体界限。**不需要发生性行为**——被触碰、被看见、暴露、贴近、被强行搂抱都算。
- 关系破裂：关系终止、决裂、反目、离开。
- 自我认知：人物如何看待自己变了，例如清白变堕落、受害者变同谋。

【输入】
${events}

【输出】
{"events":[{"sceneId":"S03","类型":"身体越界"}]}

【规则】
- 必须为输入中每一条事件输出一项，sceneId 逐字照抄，不得新增或遗漏。
- 每条只能有一个类型。
- 同一类变化在不同事件里必须用同一个类型，不要换词。
- 只输出 JSON。

${COMMON}`;
}

/** 从候选里挑关键事件并写清改变了什么。 */
export function p9Events({ candidates }) {
  return `【任务】从候选场景中挑出真正改变了人物轨迹的关键事件，并写清改变了什么。
【输入】候选（JSON 数组，每项是一场戏的摘要，含触发原因）：
${candidates}

【输出】
{"events":[{"sceneId":"S03","事件":"不超过20字，客观描述发生了什么","类型":"关系转变|权力转变|心理突破|身体越界|关系破裂|自我认知","影响":"不超过30字，改变了什么","之前":"人物的心理或关系状态","之后":"人物的心理或关系状态","持续性":"一次性|永久"}]}

【规则】
- 只能使用输入里出现过的 sceneId，不得新增；同一个 sceneId 最多出现一次。
- 候选已经按「阶段转换、权力关系改变、初次突破、状态强变化」筛过，**默认都算关键事件**；你的任务是把它们各自改变了什么写清楚，只剔除确实没有长期影响的。
- 「事件」要写清具体发生了什么：谁、在什么情形下、做了什么。可以用输入里的 beats（动作）、turnText（转折句）、motive（动机）作为事实来源。
- 禁止把"初次突破""首次发生""阶段转换"这类标签当作事件内容——那是触发原因，不是事件本身。
- 事件写客观事实，不写评价，不写"令人震惊""非常痛苦"这类词。
- 之前 / 之后写人物的心理、关系或权力状态，不写情节经过。
- 至少输出 3 条（候选不足 3 条时按实际数量）。只输出 1 条视为不合格。
- 持续性判断标准：这次改变之后，人物还会回到原来的状态吗？不会=永久，会=一次性。

${COMMON}`;
}
