export function loadTemplates() {
  try {
    return fs.existsSync(OVERRIDE_FILE) ? JSON.parse(fs.readFileSync(OVERRIDE_FILE, 'utf8')) : {};
  } catch {
    return {};
  }
}

export function saveTemplate(view, text) {
  const doc = loadTemplates();
  if (text && String(text).trim()) doc[view] = String(text);
  else delete doc[view];
  fs.mkdirSync(path.dirname(OVERRIDE_FILE), { recursive: true });
  fs.writeFileSync(OVERRIDE_FILE, JSON.stringify(doc, null, 1), 'utf8');
  return doc[view] || '';
}

export function getTemplate(view) {
  return loadTemplates()[view] || TEMPLATES[view] || '';
}

export function renderTemplate(view, vars) {
  let text = getTemplate(view);
  for (const [k, v] of Object.entries(vars || {})) text = text.split('{{' + k + '}}').join(String(v ?? ''));
  return text.replace(/\{\{[^}]+\}\}/g, '');
}


